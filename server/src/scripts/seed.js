async function seedDishes() {
  try {
    console.log(
      MONGODB_URI.startsWith('mongodb+srv')
        ? 'Connecting to MongoDB Atlas...'
        : 'Connecting to local MongoDB...'
    );
    await mongoose.connect(MONGODB_URI);
    console.log('Connected to MongoDB.');

    // Clear existing sample dishes
    const deleteResult = await Dish.deleteMany({ isSample: true });
    console.log(`Cleared ${deleteResult.deletedCount} existing sample dishes.`);

    // Insert the 12 sample dishes
    const inserted = await Dish.insertMany(sampleDishes);
    console.log(`Successfully seeded ${inserted.length} dishes into the database:`);
    inserted.forEach((d, idx) => {
      console.log(`  ${idx + 1}. [${d.restaurantName}] ${d.name} (${d.portions.length} portions, ${d.modifiers.length} modifiers)`);
    });

    console.log(`\nTotal saved dishes count: ${inserted.length}`);
    await mongoose.disconnect();
    console.log('Disconnected from MongoDB.');
    process.exit(0);
  } catch (error) {
    console.error('Seeding error:', error);
    process.exit(1);
  }
}

seedDishes();

